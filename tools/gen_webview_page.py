"""Builds lib/services/webview_page.dart from web/mediapipe_bridge.js.

Run from the hamkalaam folder:   python tools/gen_webview_page.py
Run it again whenever web/mediapipe_bridge.js changes.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
bridge = (root / "web" / "mediapipe_bridge.js").read_text(encoding="utf-8")
assert "'''" not in bridge

glue = r"""
const mp = window.hamkalaamMediaPipe;
const info = document.getElementById("hkinfo");
function post(o){ try{ Hamkalaam.postMessage(JSON.stringify(o)); }catch(e){} }
let pump = null;
window.hkInit = async function(){
  mp.setAspectRef(1.5);   // phone picture-shape correction (see mediapipe_bridge.js)
  post({type:'log', message:'module running, loading models...'});
  try { await mp.init(); post({type:'ready'}); }
  catch(e){ post({type:'error', where:'init', message:String(e)}); }
};
window.hkStart = async function(facing){
  post({type:'log', message:'asking camera...'});
  try {
    const v = document.getElementById('hk-video');
    if (v) v.style.transform = (facing === 'environment') ? 'none' : 'scaleX(-1)';
    await mp.startDetection(facing || 'user'); startPump(); post({type:'started'}); }
  catch(e){ post({type:'error', where:'start', message:String(e)}); }
};
window.hkStop = function(){
  try { mp.stopContinuous(); mp.stopDetection(); } catch(e){}
  if (pump){ clearInterval(pump); pump = null; }
  post({type:'stopped'});
};
window.hkContinuous = function(on){
  try { on ? mp.startContinuous() : mp.stopContinuous(); } catch(e){}
};
window.hkWindow = function(on){
  try {
    if (on) mp.startWindow();
    else post({type:'window', data: JSON.parse(mp.stopWindow())});
  } catch(e){ post({type:'window', data:null}); }
};
function startPump(){
  if (pump) return;
  pump = setInterval(function(){
    let hand = {}, face = {}, status = {};
    try { hand = JSON.parse(mp.getLatestResult()); } catch(e){}
    try { face = JSON.parse(mp.getLatestFace()); } catch(e){}
    try { status = JSON.parse(mp.getSegmentStatus()); } catch(e){}
    info.textContent = 'hands: ' + (hand.handCount||0) + '   face: ' + (face.detected ? 'yes' : 'no');
    post({type:'tick', hand: hand, face: face, status: status});
    let seg = mp.popSegment();
    while (seg){
      post({type:'segment', data: JSON.parse(seg)});
      seg = mp.popSegment();
    }
  }, 150);
}
window.addEventListener('error', function(e){ post({type:'error', where:'js', message:String(e.message)}); });
window.addEventListener('unhandledrejection', function(e){ post({type:'error', where:'promise', message:String(e.reason)}); });
window.addEventListener('load', function(){ window.hkInit(); });
"""

html_head = """<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
html,body{margin:0;height:100%;background:#000;overflow:hidden}
#hk-video{position:absolute;inset:0;width:100%;height:100%;object-fit:cover;transform:scaleX(-1);background:#000}
#hkinfo{display:none;position:absolute;left:8px;bottom:8px;color:#fff;font:13px sans-serif;background:rgba(0,0,0,.55);padding:3px 8px;border-radius:6px}
</style></head><body>
<video id="hk-video" autoplay playsinline muted></video>
<div id="hkinfo">loading...</div>
<script>
function hkPost(o){ try{ Hamkalaam.postMessage(JSON.stringify(o)); }catch(e){} }
hkPost({type:'log', message:'page loaded'});
setTimeout(function(){
  if (!window.hamkalaamMediaPipe) hkPost({type:'error', where:'import', message:'detector script did not load (CDN import failed)'});
}, 12000);
</script>
<script type="module">
"""
html_tail = "\n</script></body></html>\n"

page = html_head + bridge + "\n" + glue + html_tail
out = root / "lib" / "services" / "webview_page.dart"
out.write_text(
    "// GENERATED by tools/gen_webview_page.py - do not edit by hand.\n"
    "const String kWebViewPageHtml = r'''" + page + "''';\n",
    encoding="utf-8",
)
print("wrote", out, len(page), "chars")
